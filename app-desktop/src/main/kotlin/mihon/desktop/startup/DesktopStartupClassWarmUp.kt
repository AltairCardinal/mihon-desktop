package mihon.desktop.startup

import java.nio.charset.StandardCharsets

/**
 * Loads the classes the first user interface needs while the dependency graph is built.
 *
 * The start-up trace shows that the composition of the real user interface spends most of
 * its time loading and verifying around three thousand classes: the Compose runtime and
 * its text and save machinery, the serialization layer, the data and domain layer and the
 * desktop UI itself. Those classes are read from the packaged jars while the first frame
 * is composed, which is why the first real frame is late.
 *
 * Reading the same classes from a background thread while the dependency graph is built
 * moves that work off the critical path. The classes are only loaded, not initialised, so
 * no static initialiser runs earlier than it would have.
 *
 * The list is generated from a start-up trace with `-verbose:class` and is regenerated by
 * `scripts/generate-startup-warmup.ps1`.
 */
internal object DesktopStartupClassWarmUp {

    private const val RESOURCE = "desktop-startup-warmup.txt"

    /**
     * The class whose metadata the navigation library asks for while the first user
     * interface is composed.
     */
    private const val SCREEN_MODEL_CLASS = "cafe.adriel.voyager.core.model.ScreenModel"

    @Volatile
    private var warmUpThread: Thread? = null

    fun classLoader(): ClassLoader = DesktopStartupClassWarmUp::class.java.classLoader

    /** The class names that are loaded ahead of the first user interface. */
    fun classNames(): List<String> {
        val stream = DesktopStartupClassWarmUp::class.java.classLoader.getResourceAsStream(RESOURCE)
            ?: return emptyList()
        val text = stream.bufferedReader().use { it.readText() }
        return text.split('\n')
            .map { it.trim() }
            .filter { it.isNotEmpty() && !it.startsWith("#") }
    }

    /**
     * Starts the warm up on a background thread with the lowest priority.
     *
     * The warm up must never compete with the dependency graph or with the first frame.
     * A low priority daemon thread therefore does the work only while the machine is
     * idle enough, which keeps the start-up on small machines from getting slower.
     *
     * The start is recorded in the start-up trace, so the delivered trace shows when the
     * warm up went in flight relative to the rest of the start-up.
     */
    fun startAsync() {
        DesktopStartupTrace.mark("warmup-start")
        val running = warmUpThread
        if (running != null && running.isAlive) return
        val thread = Thread({
            // The warm up runs in the application's process, so an unexpected failure
            // must never escape as an uncaught exception of a background thread.
            runCatching { warmUp() }
        }, "mihon-desktop-startup-warmup").apply {
            isDaemon = true
            priority = Thread.MIN_PRIORITY
        }
        warmUpThread = thread
        thread.start()
    }

    /**
     * Loads the given classes without initialising them and returns how many could be
     * loaded. A class that cannot be resolved is skipped: the list is a hint, never a
     * requirement.
     */
    fun warmUp(names: List<String> = classNames(), loader: ClassLoader = classLoader()): Int =
        warmUpDetailed(names, loader).loadedClasses

    /**
     * Loads the given classes and prepares the reflection metadata.
     *
     * The result carries both the number of loaded classes and the qualified name the
     * reflection warm up produced, so the start-up can be observed without reading the
     * implementation.
     */
    fun warmUpDetailed(
        names: List<String> = classNames(),
        loader: ClassLoader = classLoader(),
    ): DesktopStartupWarmUpResult {
        // The reflection metadata is prepared first: the navigation library asks a
        // class for its qualified name while the first user interface is composed,
        // and with the full reflection implementation on the class path that answer
        // deserialises the class metadata on the thread that composes the interface.
        val reflectionName = warmUpReflection(loader)
        var loaded = 0
        for (name in names) {
            val resolved = runCatching { Class.forName(name, false, loader) }
            if (resolved.isSuccess) loaded++
        }
        return DesktopStartupWarmUpResult(loaded, reflectionName)
    }

    /**
     * Resolves the metadata of the class the navigation library asks for.
     *
     * With the full Kotlin reflection implementation on the class path, asking a class
     * for its qualified name deserialises the class metadata and loads several hundred
     * reflection classes. Doing that on the warm up thread keeps it off the thread that
     * composes the first user interface.
     *
     * Returns the qualified name that was resolved, or `null` when the class cannot be
     * reached. A missing class never fails the start-up.
     */
    fun warmUpReflection(loader: ClassLoader = classLoader()): String? = runCatching {
        val screenModel = Class.forName(SCREEN_MODEL_CLASS, false, loader)
        screenModel.kotlin.qualifiedName
    }.getOrNull()
}

/** What the start-up class warm up achieved. */
internal data class DesktopStartupWarmUpResult(
    val loadedClasses: Int,
    val reflectionName: String?,
)
