/**
 * Normalizes work titles for an explicit simplified/traditional merge suggestion.
 *
 * The character and phrase tables are derived from OpenCC's TSPhrases/STCharacters data (Apache-2.0).
 * They are intentionally used only for title comparison; source titles remain unchanged.
 */
object WorkTitleNormalizer {

    enum class DisplayScript {
        SIMPLIFIED,
        TRADITIONAL,
    }

    fun displayScriptForLanguageTag(languageTag: String?): DisplayScript? {
        val tag = languageTag?.trim()?.replace('_', '-')?.lowercase() ?: return null
        if (tag.isBlank() || tag == "en") return null
        return when {
            "hant" in tag ||
                (tag.substringBefore('-') == "zh" && tag.substringAfter('-', "") in setOf("tw", "hk", "mo")) ->
                DisplayScript.TRADITIONAL
            "hans" in tag ||
                (tag.substringBefore('-') == "zh" && tag.substringAfter('-', "") in setOf("cn", "sg")) ->
                DisplayScript.SIMPLIFIED
            tag == "zh" -> null
            else -> null
        }
    }

    fun matchesDisplayScript(title: String, script: DisplayScript): Boolean = when (script) {
        DisplayScript.SIMPLIFIED -> normalizeForMerge(title) == title
        DisplayScript.TRADITIONAL -> normalizeForMerge(title) != title
    }

    fun normalizeForMerge(title: String): String {
        val converted = buildString(title.length) {
            var index = 0
            while (index < title.length) {
                val phrase = phraseMappings.firstOrNull { title.startsWith(it.first, index) }
                if (phrase != null) {
                    append(phrase.second)
                    index += phrase.first.length
                } else {
                    append(traditionalToSimplified[title[index]] ?: title[index])
                    index++
                }
            }
        }
        return converted
    }

    /**
     * Produces the strict key used by the author-page presentation projection.
     *
     * Script conversion deliberately delegates to [normalizeForMerge], so the contextual phrase
     * precedence and character fallback stay shared with the existing merge evidence. Only
     * Unicode whitespace and punctuation used for typography are removed after conversion.
     */
    fun normalizeForPresentationGroup(title: String): String = normalizeForMerge(title)
        .filterNot { character ->
            character.isWhitespace() || character.category in TYPOGRAPHY_PUNCTUATION
        }

    fun isSimplifiedTraditionalVariant(first: String, second: String): Boolean {
        return first.isNotBlank() &&
            second.isNotBlank() &&
            first != second &&
            normalizeForMerge(first) == normalizeForMerge(second)
    }

